"""Generate PL confidence ROM and thresholds from the existing PS contracts."""
from pathlib import Path
import argparse,re,sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tools'))
import pose_contract as pc

def render():
    s=(ROOT/'sw/ps_uart_print/nn_confidence.h').read_text()
    scale=int(re.search(r'NN_CONF_SCALE_Q24 (\d+)',s)[1])
    vals=[int(v) for v in re.findall(r'(\d+)u',s[s.index('nn_conf_exp'):])]
    assert len(vals)==257
    lines=['// Generated by tools/gen_pl_control_constants.py; do not edit.']
    for name in ('POSE_MIN_CONF','POSE_HOLD_CONF','POSE_CONFIRM_WINDOWS','POSE_REST_WINDOWS','POSE_UNCERTAIN_WINDOWS'):
        lines.append(f'localparam integer {name} = {getattr(pc,name)};')
    lines.append(f"localparam [31:0] CONF_SCALE_Q24 = 32'd{scale};")
    lines+=['function [20:0] confidence_exp;','input [8:0] address;','begin','case(address)']+[f"9'd{i}: confidence_exp=21'd{v};" for i,v in enumerate(vals)]+['default: confidence_exp=0;','endcase','end','endfunction','']
    return '\n'.join(lines)
if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args()
    target=ROOT/'src/rtl/emg_control_constants.vh'
    text=render()
    if a.check:assert target.read_text()==text,'PL constants are stale; regenerate'
    else:target.write_text(text,encoding='ascii')
    print('PL control constants: PS confidence table and pose thresholds match')

