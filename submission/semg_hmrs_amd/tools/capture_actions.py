"""Acquisition labels; IDs 0..5 retain their historical meaning.

These are manual ground-truth labels, NOT the five-class PL result protocol.
"""
import argparse
from pathlib import Path

SCHEMA = 2
# symbol, machine label, LCD label, execution definition
ACTIONS = (
    ('NONE', 'none', '未标注', 'Unlabeled or transition; exclude from fitting'),
    ('REST', 'rest', '放松', 'Natural relaxed hand and neutral wrist'),
    ('OPEN', 'open_hand', '张手', 'All fingers extended, wrist neutral'),
    ('FIST', 'fist', '握拳', 'Comfortable fist, wrist neutral'),
    ('FLEX', 'wrist_flex', '屈腕', 'Wrist flexion, fingers naturally relaxed'),
    ('EXTEND', 'wrist_extend', '伸腕', 'Wrist extension, fingers naturally relaxed'),
    ('THUMB', 'thumb_extend', '拇指伸出', 'Only thumb extended; other fingers naturally flexed; wrist neutral'),
    ('INDEX', 'index_extend', '食指伸出', 'Only index extended; other fingers naturally flexed; wrist neutral'),
    ('MIDDLE', 'middle_extend', '中指伸出', 'Only middle extended; other fingers naturally flexed; wrist neutral'),
    ('FIST_FLEX', 'fist_wrist_flex', '握拳屈腕', 'Maintain fist while flexing wrist'),
    ('FIST_EXTEND', 'fist_wrist_extend', '握拳伸腕', 'Maintain fist while extending wrist'),
    ('THUMB_INDEX', 'thumb_index_extend', '拇食伸出', 'Thumb and index extended; other fingers flexed; wrist neutral'),
    ('THUMB_MIDDLE', 'thumb_middle_extend', '拇中伸出', 'Thumb and middle extended; other fingers flexed; wrist neutral'),
    ('INDEX_MIDDLE', 'index_middle_extend', '食中伸出', 'Index and middle extended; other fingers flexed; wrist neutral'),
    ('THUMB_INDEX_MIDDLE', 'thumb_index_middle_extend', '拇食中伸出', 'Thumb/index/middle extended; ring/little flexed; wrist neutral'),
)
LABELS = [a[1] for a in ACTIONS[1:]]
LEGACY_CLASSES = LABELS[:5]
CLASS_SETS = {'legacy5': LEGACY_CLASSES, 'gestures14': LABELS}
ACTION_BY_ID = {i: row[1] for i, row in enumerate(ACTIONS)}
KEYS = '123456789abcde'


def label_for_command(command):
    """Console accepts 1..14; a..e are single-key aliases for 10..14."""
    command = command.strip().lower()
    if command == '0':
        return 'none'
    if command in KEYS and len(command) == 1:
        return LABELS[KEYS.index(command)]
    if command.isascii() and command.isdigit() and 1 <= int(command) <= len(LABELS):
        return LABELS[int(command)-1]
    return None


def render_header():
    lines = ['/* Generated by tools/capture_actions.py; manual labels, not inference IDs. */',
             '#ifndef CAPTURE_ACTIONS_H', '#define CAPTURE_ACTIONS_H',
             f'#define SD_ACTION_SCHEMA {SCHEMA}u', f'#define SD_ACTION_COUNT {len(LABELS)}u',
             '#define SD_LABEL_PAGES 3u', '#define SD_LABELS_PER_PAGE 5u', 'enum {']
    lines += [f'    SD_ACTION_{row[0]} = {i},' for i, row in enumerate(ACTIONS)]
    lines += ['};', '#ifdef SD_CAPTURE_LABEL_UI', 'static const char *const sd_action_names_zh[] = {']
    lines += [f'    "{row[2]}",' for row in ACTIONS]
    lines += ['};', 'static const char *const sd_label_page_names[] = {"基本动作", "单指腕部", "多指组合"};',
              '#endif', '#endif', '']
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    path = Path(__file__).resolve().parents[1]/'sw/ps_uart_print/capture_actions.h'
    expected = render_header()
    if args.check:
        if path.read_text(encoding='utf-8') != expected:
            raise SystemExit('Capture label header is stale')
        print('TEST_PASS capture label header matches Python schema')
    else:
        path.write_text(expected, encoding='utf-8')
        print(path)


if __name__ == '__main__':
    main()

