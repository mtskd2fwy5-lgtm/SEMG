"""Generate ordered D2048 seed7 memories: legacy Q16 and new Q32."""
import argparse
import hashlib
from pathlib import Path

import numpy as np
from audit_hdc import memories

ROOT=Path(__file__).resolve().parents[1]


def render():
    lines=['/* Generated by tools/gen_hdc_memory.py: bit1=+1, little-endian bits. */',
           '#ifndef HDC_MEMORY_H','#define HDC_MEMORY_H']
    arrays=[]
    for levels in (16,32):
        cim,vim=memories(2048,levels,7,ordered=True)
        arrays += [('hdc_cim' if levels==16 else 'hdc_cim32',cim),
                   ('hdc_vim' if levels==16 else 'hdc_vim32',vim)]
    for name,a in arrays:
        packed=np.packbits(a>0,axis=1,bitorder='little').view('<u4')
        lines.append(f'static const uint32_t {name}[{len(a)}][64]={{')
        for row in packed:
            lines.append('    {'+','.join(f'0x{int(v):08x}u' for v in row)+'},')
        lines.append('};')
    lines.extend(['#endif',''])
    return '\n'.join(lines)


if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check',action='store_true');args=ap.parse_args()
    path=ROOT/'sw/ps_uart_print/hdc_memory.h';text=render()
    import re
    words=re.findall(r'0x([0-9a-f]{8})u',text)
    mem='\n'.join(words+['00000000']*(4096-len(words)))+'\n'
    mem_path=ROOT/'data/models/hdc_memory.mem'
    if args.check:
        assert path.read_text(encoding='utf-8')==text,'HDC memory is stale'
        assert mem_path.read_text(encoding='utf-8')==mem,'PL HDC memory is stale'
    else:
        path.write_text(text,encoding='utf-8')
        mem_path.write_text(mem,encoding='utf-8')
    print('TEST_PASS HDC memory',hashlib.sha256(text.encode()).hexdigest())

