#!/usr/bin/env python3
"""Quantize the trained multi-wear board model for the PL inference BRAM."""
import argparse
import json
from pathlib import Path

import joblib
import numpy as np
from sklearn.metrics import accuracy_score

from export_int8 import Int8MLP, build_mem, quantize_model
from train_board_model import ROOT, feature_windows, read_capture, remove_spike_windows


def write_confidence_header(qp, path):
    """Export exp(-x) lookup and this model's logit scale for bare-metal PS."""
    scale = int(round(float(qp["logits_scale"]) * 16 * (1 << 24)))
    lut = np.rint(np.exp(-np.arange(257) / 16) * (1 << 20)).astype(int)
    rows = [", ".join(str(v) + "u" for v in lut[i:i + 8]) for i in range(0, len(lut), 8)]
    text = ("/* Generated by tools/export_board_int8.py from quant_params.json. */\n"
            "#ifndef NN_CONFIDENCE_H\n#define NN_CONFIDENCE_H\n"
            f"#define NN_CONF_SCALE_Q24 {scale}u\n"
            "/* Uncalibrated softmax, exp(-x) Q20 sampled every 1/16. */\n"
            "static const u32 nn_conf_exp[257] = {\n    " + ",\n    ".join(rows) + "\n};\n#endif\n")
    path.write_text(text, encoding="ascii")


def capture_features(path, training=False):
    x, y = read_capture(path)
    fx, fy, _ = feature_windows(x, y)
    if training:
        fx, fy, _, _ = remove_spike_windows(fx, fy)
    return fx, fy


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--model", default="data/models/emg008_009_multiwear.joblib")
    ap.add_argument("--out-dir", default="data/models/nn_int8_board_multiwear")
    ap.add_argument("--metrics", default="data/metrics/nn_int8_board_multiwear.json")
    ap.add_argument("--confidence-header-only", action="store_true")
    ap.add_argument("--train-csvs", nargs="+", default=[
        "report/emg008_20261022/EMG008_processed.csv",
        "report/emg009_20261022/EMG009_processed.csv",
        "report/emg012_20261022/EMG012_processed.csv",
        "report/emg013_20261022/EMG013_processed.csv",
        "report/emg014_20261022/EMG014_processed.csv",
        "report/emg015_20261022/EMG015_processed.csv",
        "report/emg016_20261022/EMG016_processed.csv",
    ])
    ap.add_argument("--test-csv", default="report/emg017_20261022/EMG017_processed.csv")
    args = ap.parse_args()

    if args.confidence_header_only:
        qp = json.loads((ROOT / args.out_dir / "quant_params.json").read_text(encoding="utf-8"))
        write_confidence_header(qp, ROOT / "sw/ps_uart_print/nn_confidence.h")
        print("generated sw/ps_uart_print/nn_confidence.h; model weights unchanged")
        return

    model = joblib.load(ROOT / args.model)
    captures = [capture_features(ROOT / p, training=True) for p in args.train_csvs]
    calib_x = np.concatenate([x for x, _ in captures])
    test_x, test_y = capture_features(ROOT / args.test_csv)
    qp = quantize_model(model, calib_x)
    int8 = Int8MLP(qp)
    float_pred = model.predict(test_x)
    int8_pred = int8.predict(test_x)
    out_dir = ROOT / args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    demo = calib_x[:64]
    with (out_dir / "tb_inputs.mem").open("w", encoding="ascii", newline="\n") as fh:
        for value in demo.reshape(-1):
            fh.write(f"{int(value) & 0xFFFFFFFF:08x}\n")
    with (out_dir / "tb_logits.mem").open("w", encoding="ascii", newline="\n") as fh:
        for value in int8.forward(demo).reshape(-1):
            fh.write(f"{int(value) & 0xFFFFFFFF:08x}\n")
    qp["mem_layout"] = __import__("export_int8").MEM_LAYOUT
    qp["preprocessing"] = {
        "sample_rate_hz": 4000, "channels": 8, "window_samples": 400,
        "hop_samples": 100, "features": ["MAV", "WL", "Energy", "ZC", "SSC"],
        "signal": "processed: notch50 + comb50 + HP20 + LP215",
    }
    (out_dir / "quant_params.json").write_text(json.dumps(qp, indent=2), encoding="utf-8")
    (out_dir / "nn_int8_weights.mem").write_text(build_mem(qp), encoding="ascii")
    write_confidence_header(qp, ROOT / "sw/ps_uart_print/nn_confidence.h")
    metrics = {
        "source_model": args.model,
        "calibration_windows": int(len(calib_x)),
        "test_capture": args.test_csv,
        "test_windows": int(len(test_y)),
        "float_accuracy": float(accuracy_score(test_y, float_pred)),
        "int8_accuracy": float(accuracy_score(test_y, int8_pred)),
        "float_int8_agreement": float(np.mean(float_pred == int8_pred)),
        "classes": qp["classes"],
        "output_dir": args.out_dir,
    }
    metrics_path = ROOT / args.metrics
    metrics_path.parent.mkdir(parents=True, exist_ok=True)
    metrics_path.write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    print(json.dumps(metrics, indent=2))


if __name__ == "__main__":
    main()

