"""Generate native-size, 4-bit Source Han Sans LCD glyphs (requires Pillow)."""
from pathlib import Path
import hashlib
import re
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'third_party/fonts/source-han-sans/SourceHanSansCN-Regular.otf'
SOURCES = ['main.c', 'lcd_ui.h', 'lcd_home.h', 'lcd_settings.h', 'lcd_waveform.h', 'lcd_rehab.h', 'lcd_channel_quality.h', 'capture_actions.h', 'lcd_hdc.h', 'lcd_hand.h', 'lcd_virtual.h']
SIZES = (16, 20, 24, 32)


def font_metrics(font, chars):
    boxes = [font.getbbox(char, anchor='ls') for char in chars if char != ' ']
    ascent = -min(box[1] for box in boxes)
    descent = max(box[3] for box in boxes)
    return ascent, ascent + descent


def render_glyph(char, font, size, baseline, height):
    """Every script uses the same font size, baseline and vertical bearings."""
    box = font.getbbox(char, anchor='ls')
    if char != ' ' and (box is None or box[2] <= box[0]):
        raise ValueError(f'Missing glyph U+{ord(char):04X}')
    advance = (18 if size == 32 else 12) if ord(char) < 128 else size + 1
    width = max(1, box[2] - box[0])
    tile = Image.new('L', (max(size, width), height))
    ImageDraw.Draw(tile).text((-box[0], baseline), char,
                             font=font, fill=255, anchor='ls')
    tile = tile.crop((0, 0, width, height))
    # Retain the established horizontal advances without changing the baseline.
    if width > advance - 1:
        tile = tile.resize((advance - 1, height), Image.Resampling.LANCZOS)
    image = Image.new('L', (size, height))
    image.paste(tile, (0, 0))
    return image


def main():
    text = ''.join((ROOT / 'sw/ps_uart_print' / p).read_text(encoding='utf-8')
                   for p in SOURCES)
    chars = sorted(set(re.findall(r'[\u4e00-\u9fff\u00b1]', text)) |
                   {chr(cp) for cp in range(32, 127)})
    fonts = {size: ImageFont.truetype(str(FONT), size) for size in SIZES}
    metrics = {size: font_metrics(font, chars) for size, font in fonts.items()}
    glyph_bytes = sum(size * metrics[size][1] // 2 for size in SIZES)
    lines = ['/* Generated by tools/gen_hz_glyphs.py. Do not edit.',
             ' * Source Han Sans CN Regular; SIL Open Font License 1.1.',
             f' * Font SHA256: {hashlib.sha256(FONT.read_bytes()).hexdigest()}',
             ' * Common baseline per size; two 4-bit coverage samples per byte. */',
             '#ifndef LCD_FONT_ZH_H', '#define LCD_FONT_ZH_H',
             'static const struct { u16 size, height, baseline, offset; } lcd_font_metrics[] = {']
    offset = 0
    for size in SIZES:
        baseline, height = metrics[size]
        lines.append(f'    {{{size}, {height}, {baseline}, {offset}}},')
        offset += size * height // 2
    lines.extend(['};', f'static const struct {{ u16 cp; u8 g[{glyph_bytes}]; }} lcd_zh[] = {{'])
    for char in chars:
        data = []
        for size, font in fonts.items():
            baseline, height = metrics[size]
            image = render_glyph(char, font, size, baseline, height)
            coverage = [(p*15+127)//255 for p in image.tobytes()]
            data.extend((coverage[i] << 4) | coverage[i+1]
                        for i in range(0, len(coverage), 2))
        assert len(data) == glyph_bytes
        lines.append(f'    {{0x{ord(char):04X}, {{')
        for i in range(0, len(data), 24):
            lines.append('        '+','.join(f'0x{v:02X}' for v in data[i:i+24])+',')
        lines.append('    }},')
    lines.extend(['};', '#define LCD_ZH_N (sizeof(lcd_zh)/sizeof(lcd_zh[0]))', '#endif', ''])
    output = ROOT / 'sw/ps_uart_print/lcd_font_zh.h'
    output.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Source Han Sans: {len(chars)} glyphs, sizes {SIZES}, {output}')


if __name__ == '__main__':
    main()
