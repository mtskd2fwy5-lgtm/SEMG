"""Fit a fixed, unlabeled NMF basis on EMG008/009 for the PS LCD prototype.

This is a visualization model, not a force estimator or gesture classifier.
Reuses nmf_validate's 100 ms / 25 ms MAV and online dictionary fitting.
The firmware holds the resulting dictionary fixed and only solves C.
"""
import hashlib
import json
from pathlib import Path

import numpy as np
from nmf_validate import envelopes, load_csv, online_nmf

ROOT = Path(__file__).resolve().parents[1]


def fixed_float(E, W):
    """Double precision reference for firmware projection/eight-update solve.

    E is mean absolute ADC counts. Floor matches one Q8 coefficient unit;
    dictionary/Gram remain double precision to expose quantization error.
    """
    gram = W.T @ W
    result = []
    for e in E:
        numerator = W.T @ e
        c = numerator / 3
        for _ in range(8):
            positive = np.maximum(c, 1 / 256)
            c = positive * numerator / np.maximum(gram @ positive, 1e-12)
        result.append(c.copy())
    return np.asarray(result)


def main():
    inputs = [ROOT / f'report/emg{i:03d}_20261022/EMG{i:03d}_processed.csv'
              for i in (8, 9)]
    blocks = []
    for path in inputs:
        signal, _, filtered = load_csv(str(path))
        if not filtered:
            raise ValueError(f'Expected final board-processed capture: {path}')
        block, _ = envelopes(signal, 4000, prefiltered=True)
        blocks.append(block)
    E = np.concatenate(blocks)
    _, W, _ = online_nmf(E, 3, 2, 50, .999, 7)
    weights = np.rint(W * 32768).astype(int)
    # Compute display scale for the actual fixed dictionary, rather than
    # using activations collected while the dictionary was still changing.
    C = fixed_float(E, weights / 32768)
    refs = np.maximum(1, np.ceil(np.percentile(C, 99, axis=0))).astype(int)
    header = ROOT / 'sw/ps_uart_print/synergy_nmf_model.h'
    rows = ',\n'.join('    {' + ','.join(f'{v}u' for v in row) + '}'
                       for row in weights)
    header.write_text(
        '/* Generated by tools/export_synergy_model.py; EMG008/009. */\n'
        '#ifndef EMG_SYNERGY_NMF_MODEL_H\n#define EMG_SYNERGY_NMF_MODEL_H\n'
        'static const u16 synergy_w_q15[8][3] = {\n' + rows + '\n};\n'
        '/* 99th percentile of fixed-W coefficients in Q8 mean ADC counts. */\n'
        'static const u32 synergy_display_ref[3] = {' +
        ','.join(f'{v * 256}u' for v in refs) + '};\n#endif\n', encoding='utf-8')
    output = ROOT / 'report/synergy_20261023'
    output.mkdir(exist_ok=True)
    manifest = {
        'inputs': [{'path': str(p.relative_to(ROOT)),
                    'sha256': hashlib.sha256(p.read_bytes()).hexdigest()}
                   for p in inputs],
        'windows': len(E), 'fit_seed': 7, 'window_samples': 400,
        'hop_samples': 100, 'fit_c_iters': 2, 'fit_w_period': 50,
        'fit_lam': .999, 'firmware': 'fixed W, fresh projection and eight C iterations per window',
        'weight_q15': weights.tolist(), 'display_ref_q8': (refs * 256).tolist(),
        'scope': 'relative activity visualization; no force/accuracy claim',
    }
    (output / 'model.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    print(f'Exported {header}; {len(E)} windows; fixed-W display references {refs.tolist()}')


if __name__ == '__main__':
    main()
